test('plan windows belong to the sign-in they were reported under: a new sign-in starts clean', async () => {
  const { usageOf } = await import('./runner.ts')
  const { setIdentity, markLimited, limitedUntil } = await import('./providers.ts')
  const { state } = await import('./store.ts')
  const spent = { five: { used: 0.95, resetsAt: 9e9 }, seven: { used: 0.96, resetsAt: 9e9 }, at: '2026-11-11T15:03:48Z' }
  state.usageBy = { person: { ...spent, who: 'login:me@gmail.com|gmail' } }
  setIdentity('person', 'login:me@gmail.com|gmail')
  assert.equal(usageOf('person')?.seven?.used, 0.96)
  markLimited('person', Date.now() + 3600_000)
  setIdentity('person', 'login:me@work.example|Acme') // signed in again, as someone else
  assert.equal(usageOf('person'), undefined) // the Gmail plan's windows aren't this one's
  assert.equal(limitedUntil('person'), undefined) // nor its limit
  state.usageBy = { person: { ...spent } } // from before sign-ins were noted
  assert.equal(usageOf('person'), undefined)
})
