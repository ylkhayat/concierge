// Linear, read-only: the tickets assigned to you, bucketed the way the exec command picks them.
// Uses LINEAR_API_KEY; the exec command itself does every write (state, labels, comments).
import { config } from './config.ts'

export type Ticket = {
  id: string // "AC-1234"
  title: string
  url: string
  description: string
  state: string // Linear state name
  stateType: string // backlog | unstarted | started | completed | canceled | triage
  priority: number // 0 none, 1 urgent … 4 low
  labels: string[]
  team: string
  branch: string // Linear's gitBranchName
  updatedAt: string
  createdAt: string
  agentWaiting: boolean // labelled Refinement and the latest comment is the agent's: your turn
  lastComment?: { by: string; at: string; body: string; threadId: string } // threadId: the thread to reply in (Linear threads are one level deep)
  prs: { repo: string; number: number; url: string; title?: string }[] // GitHub PRs linked on the ticket
  handedTo?: string // not assigned to you any more (you handed it over): who has it
  closed?: boolean // done or cancelled: kept only while something here still names it
  doneAt?: string // when it was done or cancelled: the list keeps it under Done for a few days
  project?: string // the Linear project it belongs to: product work; none is a side quest (bugs, tech debt, feedback)
  source?: 'github' // a GitHub issue (issues.ts), not a Linear ticket
}

export const hasKey = () => !!process.env.LINEAR_API_KEY

export async function gql<T>(query: string, variables: object = {}): Promise<T> {
  const res = await fetch('https://api.linear.app/graphql', {
    method: 'POST',
    headers: { Authorization: process.env.LINEAR_API_KEY ?? '', 'Content-Type': 'application/json' },
    body: JSON.stringify({ query, variables }),
  })
  const json = await res.json() as { data?: T; errors?: { message: string }[] }
  if (!json.data) throw new Error(`Linear: ${json.errors?.[0]?.message ?? res.status}`)
  return json.data
}

const AGENT_MARK = /Generated by Claude Code/i

const FIELDS = `identifier title url description priority updatedAt createdAt completedAt canceledAt branchName
  state { name type } team { key } labels { nodes { name } } assignee { name isMe } project { name }
  comments(first: 1, orderBy: createdAt) { nodes { id body createdAt user { name } parent { id } } } # newest first
  attachments { nodes { url title } }`

function toTicket(n: any): Ticket {
  const labels = n.labels.nodes.map((l: { name: string }) => l.name)
  const c = n.comments.nodes[0]
  return {
    id: n.identifier, title: n.title, url: n.url, description: n.description ?? '', state: n.state.name, stateType: n.state.type,
    priority: n.priority, labels, team: n.team.key, ...(n.project?.name && { project: n.project.name }), branch: n.branchName, updatedAt: n.updatedAt, createdAt: n.createdAt,
    agentWaiting: labels.includes('Refinement') && !!c && AGENT_MARK.test(c.body),
    lastComment: c && { by: c.user?.name ?? 'someone', at: c.createdAt, body: c.body.slice(0, 2000), threadId: c.parent?.id ?? c.id },
    prs: n.attachments.nodes.flatMap((a: { url: string; title?: string }) => {
      const m = a.url.match(/github\.com\/([^/]+\/[^/]+)\/pull\/(\d+)/)
      return m ? [{ repo: m[1], number: Number(m[2]), url: a.url, title: a.title }] : []
    }),
    ...(!n.assignee?.isMe && { handedTo: n.assignee?.name ?? 'nobody' }),
    ...(['completed', 'canceled', 'duplicate'].includes(n.state.type) && { closed: true, doneAt: n.completedAt ?? n.canceledAt ?? n.updatedAt }),
  }
}

/** How long a done or cancelled ticket (or a merged or closed PR) stays on the list, under Done. */
export const DONE_DAYS = 3

/** Issues assigned to you in Triage, Todo or a started state (In Progress, In Review), in the watched teams. */
export async function myTickets(): Promise<Ticket[]> {
  const teams = config.exec.teams
  if (!hasKey()) throw new Error('Linear isn\'t connected: add your API key in Settings → Machines')
  // the ones done or cancelled lately too: the list keeps them under Done for DONE_DAYS, then lets them go
  const since = new Date(Date.now() - DONE_DAYS * 86_400_000).toISOString()
  const ask = (filter: string, fields = FIELDS) => gql<{ viewer: { assignedIssues: { nodes: any[] } } }>(`
    query($teams: [String!]) { viewer { assignedIssues(first: 250, filter: { team: { key: { in: $teams } }, ${filter} }) { nodes { ${fields} } } } }`,
    { teams: teams.length ? teams : null })
  const open = 'state: { type: { in: ["triage", "backlog", "unstarted", "started"] } }'
  // Linear refusing the wider filter must not empty the list: then the open ones only, as before
  const data = await ask(`or: [{ ${open} }, { completedAt: { gt: "${since}" } }, { canceledAt: { gt: "${since}" } }]`)
    .catch((e) => { console.warn(`linear: done tickets left out (${(e as Error).message.split('\n')[0]})`); return ask(open, FIELDS.replace(' completedAt canceledAt', '')) })
  return data.viewer.assignedIssues.nodes.map(toTicket)
}

/** Tickets by id, whoever has them and whatever their state; one deleted or out of reach is left out. */
export async function ticketsById(ids: string[]): Promise<Ticket[]> {
  if (!ids.length) return []
  const q = ids.map((id, i) => `t${i}: issue(id: ${JSON.stringify(id)}) { ${FIELDS} }`).join('\n')
  // a missing one fails only its own field: the rest still come back
  const res = await fetch('https://api.linear.app/graphql', {
    method: 'POST', headers: { Authorization: process.env.LINEAR_API_KEY ?? '', 'Content-Type': 'application/json' }, body: JSON.stringify({ query: `{ ${q} }` }),
  })
  const json = await res.json() as { data?: Record<string, any>; errors?: { message: string }[] }
  if (!json.data) throw new Error(`Linear: ${json.errors?.[0]?.message ?? res.status}`)
  return Object.values(json.data).filter(Boolean).map(toTicket)
}

export type Bucket = 'needs-you' | 'tend' | 'stalled' | 'in-progress' | 'todo' | 'triage' | 'backlog' | 'shipped' | 'handed' | 'closed'

/** Mirrors the exec command's pick order. `pr.actionable`: the linked PR needs tending (red CI or an open thread waiting on you). */
export function bucketOf(t: Ticket, pr?: { actionable: boolean }, now = Date.now()): Bucket {
  if (t.closed) return 'closed' // kept for what names it (a standup, a run), never on the list
  if (t.handedTo) return 'handed' // someone else's now: yours to drive by hand, never picked, never waiting on you
  if (t.agentWaiting) return 'needs-you'
  const s = t.state.toLowerCase()
  if (s.includes('review')) return pr?.actionable ? 'tend' : 'shipped'
  if (t.stateType === 'triage') return 'triage' // never auto-picked; run by name from the board
  if (t.stateType === 'backlog') return 'backlog' // like triage: never auto-picked
  if (t.stateType === 'started') return now - new Date(t.updatedAt).getTime() > 24 * 3600_000 ? 'stalled' : 'in-progress'
  return 'todo'
}

/** A run that ended and left you decisions or steps waits on you, like a question on Linear does. */
export const handedBack = (run: { state: string; next?: Parameters<typeof pendingOf>[0] } | undefined, b: Bucket): Bucket =>
  b !== 'closed' && b !== 'handed' && (run?.state === 'done' || run?.state === 'failed') && pendingOf(run.next) > 0 ? 'needs-you' : b

/** Post a comment as you (the key's owner), in `parentId`'s thread when given. Only for text you wrote yourself. */
export async function postComment(identifier: string, body: string, parentId?: string): Promise<string> {
  const r = await gql<{ commentCreate: { success: boolean; comment: { url: string } } }>(
    'mutation($issueId: String!, $body: String!, $parentId: String) { commentCreate(input: { issueId: $issueId, body: $body, parentId: $parentId }) { success comment { url } } }',
    { issueId: identifier, body, parentId: parentId ?? null })
  if (!r.commentCreate.success) throw new Error('Linear did not accept the comment')
  return r.commentCreate.comment.url
}

/** Assign a ticket to you (the key's user); nothing to do when it already is. */
export async function assignToMe(identifier: string) {
  const r = await gql<{ viewer: { id: string }; issue: { id: string; assignee: { id: string } | null } }>(
    'query($id: String!) { viewer { id } issue(id: $id) { id assignee { id } } }', { id: identifier })
  if (r.issue.assignee?.id === r.viewer.id) return
  const u = await gql<{ issueUpdate: { success: boolean } }>(
    'mutation($id: String!, $a: String!) { issueUpdate(id: $id, input: { assigneeId: $a }) { success } }', { id: r.issue.id, a: r.viewer.id })
  if (!u.issueUpdate.success) throw new Error('Linear did not accept the assignment')
}

/** A ticket as the explanation reads it: what was asked, and the discussion (the analysis) under it. Read only. */
export async function ticketBrief(identifier: string): Promise<string | undefined> {
  if (!hasKey()) return undefined
  const d = await gql<{ issue: { identifier: string; title: string; description?: string; labels: { nodes: { name: string }[] }; comments: { nodes: { body: string; user?: { name: string } }[] } } | null }>(`
    query($id: String!) { issue(id: $id) { identifier title description labels { nodes { name } } comments(last: 6) { nodes { body user { name } } } } }`, { id: identifier }).catch(() => undefined)
  const i = d?.issue
  if (!i) return undefined
  return [`${i.identifier} "${i.title}"${i.labels.nodes.length ? ` [${i.labels.nodes.map((l) => l.name).join(', ')}]` : ''}`,
    (i.description ?? '(no description)').slice(0, 2500),
    ...i.comments.nodes.map((c) => `--- comment by ${c.user?.name ?? 'someone'}:\n${c.body.slice(0, 1200)}`)].join('\n')
}
