test('a thread waits on you unless its last word is yours or the reviewer signing off', async () => {
  const { waitsOnYou } = await import('./github.ts')
  const mark = '[![Generated by Claude Code](https://img.shields.io/badge/x)](https://claude.com/claude-code)\n\n'
  const c = (login: string, body: string) => ({ author: { login }, body })
  assert.equal(waitsOnYou(c('me', 'done'), 'me'), false)
  assert.equal(waitsOnYou(c('lee', mark + '![fixed](https://img.shields.io/badge/fixed-1a7f37) **AI;DR** works now'), 'me'), false)
  assert.equal(waitsOnYou(c('lee', "![won't fix](x) fine by me"), 'me'), false)
  assert.equal(waitsOnYou(c('lee', mark + '![withdrawn](x) Fair: matches the file family. Withdrawn.'), 'me'), false)
  assert.equal(waitsOnYou(c('sam', 'LGTM, thanks'), 'me'), false)
  assert.equal(waitsOnYou(c('lee', mark + '![needs your call](x) which one?'), 'me'), true)
  assert.equal(waitsOnYou(c('lee', '![MEDIUM](x) ![blocking](x) this still drops the save'), 'me'), true)
  assert.equal(waitsOnYou(c('jonas', 'Why not reuse the existing helper?'), 'me'), true)
  // an acknowledgement closes it on your side: the reviewer resolves (#4564 went round in circles on these)
  assert.equal(waitsOnYou(c('pg', 'Confirmed in bb87487: a failed request now lands on "We couldn\'t check the call".\n\n🤖 Drafted by Claude Code'), 'me'), false)
  assert.equal(waitsOnYou(c('pg', "Agreed, that's a fair trade for the first version."), 'me'), false)
  // unless it asks for something more
  assert.equal(waitsOnYou(c('pg', 'Agreed, but could the timeout also show the retry?'), 'me'), true)
  assert.equal(waitsOnYou(c('pg', 'Confirmed. **[LOW] Question:** the countdown is quiet now'), 'me'), true)
})

test('stamper dates each stream line once, across chunk boundaries, and keeps it valid JSON', async () => {
  const { stamper } = await import('./runner.ts')
  const st = stamper()
  const out = st('{"type":"a"}\n{"type":"b","x":{"y":') + st('{"z":1}}}\n{"timestamp":"t","type":"c"}\n')
  const lines = out.trim().split('\n').map((l) => JSON.parse(l))
  assert.deepEqual(lines.map((l) => l.type), ['a', 'b', 'c'])
  assert.ok(lines[0].timestamp && lines[1].timestamp)
  assert.equal(lines[2].timestamp, 't') // already dated: left alone
})

test('a review already seen is never announced again, whichever sync saw it first', async () => {
  const { changesOf } = await import('./github.ts')
  const base = { id: 'o/r#1', mine: true, headSha: 'a', seenReviews: ['r1'] } as never
  const reviews = [{ id: 'r1', who: 'ann', state: 'APPROVED' }]
  assert.deepEqual(changesOf(base, base, 'me', { reviews }), [])
  // an old-format list (GraphQL node ids) records without announcing
  const legacy = { ...(base as object), seenReviews: ['PRR_kwDOOxkpTc8AAAABS_xtGQ'] } as never
  assert.deepEqual(changesOf(legacy, legacy, 'me', { reviews }), [])
})

