test('asking to review again: not those whose latest verdict is an approval', async () => {
  const { approvedNow } = await import('./github.ts')
  const r = (who: string, state: string) => ({ who, state })
  assert.deepEqual([...approvedNow([r('sam', 'CHANGES_REQUESTED'), r('sam', 'APPROVED'), r('sam', 'COMMENTED')])], ['sam']) // approved since: a later comment changes nothing
  assert.deepEqual([...approvedNow([r('lee', 'APPROVED'), r('lee', 'CHANGES_REQUESTED')])], []) // asked for changes after approving
  assert.deepEqual([...approvedNow([r('ann', 'COMMENTED')])], [])
})

test("each reviewer's latest word for the header: a verdict outlasts a later comment, an open request shows, no bots or author", async () => {
  const { verdictsOf } = await import('./github.ts')
  const r = (who: string, state: string) => ({ who, state })
  assert.deepEqual(verdictsOf([r('sam', 'APPROVED'), r('sam', 'COMMENTED'), r('ann', 'COMMENTED'), r('lee', 'CHANGES_REQUESTED'), r('me', 'COMMENTED'), r('ci[bot]', 'COMMENTED')], new Set(['bob']), 'me'),
    [{ who: 'lee', state: 'CHANGES_REQUESTED' }, { who: 'bob', state: 'REQUESTED' }, { who: 'ann', state: 'COMMENTED' }, { who: 'sam', state: 'APPROVED' }])
  assert.deepEqual(verdictsOf([r('sam', 'APPROVED')], new Set(['sam']), 'me'), [{ who: 'sam', state: 'REQUESTED' }]) // asked again since
})

