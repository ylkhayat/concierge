// Turns: how a PR changed direction, push by push. On each new head, what reviewers asked and what the author
// answered since the push before, plus the commits that are new, go to one lean Haiku call that names at most three
// changes of direction in a few words each: changed, held (a reviewer's point kept as it was, and why) or dropped.
// For your PRs and the ones you review. Nothing new to go on (a rebase, a push nobody asked for): no call.
import { method } from './method.ts'
import { tmpdir } from 'node:os'
import { providerFor, spawnAgent, tokensOf, type ProviderId } from './providers.ts'
import { graphql } from './github.ts'
import { save, state, type Pr, addSpend } from './store.ts'

export type TurnLine = { kind: 'changed' | 'held' | 'dropped'; text: string; who?: string; url?: string }
export type Turn = { at: string; from: string; to: string; lines: TurnLine[]; costUsd: number }
export type Turns = { sha: string; at: string; seen?: string[]; list: Turn[] }

const schema = {
  type: 'object', additionalProperties: false, required: ['lines'],
  properties: { lines: { type: 'array', maxItems: 3, items: { type: 'object', additionalProperties: false, required: ['kind', 'text'], properties: {
    kind: { type: 'string', enum: ['changed', 'held', 'dropped'] }, text: { type: 'string' }, who: { type: 'string' }, url: { type: 'string' },
  } } } },
}

type Said = { who: string; body: string; at: string; url: string }
type Node = { author: { __typename: string; login: string } | null; body: string; createdAt: string; url: string }
const READ = `query($o:String!,$r:String!,$n:Int!){ repository(owner:$o,name:$r){ pullRequest(number:$n){
  commits(last:100){nodes{commit{messageHeadline messageBody}}}
  reviewThreads(first:100){nodes{comments(first:30){nodes{author{__typename login} body createdAt url}}}}
  comments(last:50){nodes{author{__typename login} body createdAt url}}
  reviews(last:30){nodes{author{__typename login} body createdAt: submittedAt url}} }}}`

async function read(pr: Pr) {
  const [o, r] = pr.repo.split('/')
  const d = await graphql<{ repository: { pullRequest: any } }>(READ, { o, r, n: pr.number })
  const p = d.repository.pullRequest
  const said: Node[] = [...p.reviewThreads.nodes.flatMap((t: any) => t.comments.nodes), ...p.comments.nodes, ...p.reviews.nodes]
  return {
    commits: p.commits.nodes.map((c: any) => ({ head: c.commit.messageHeadline as string, body: String(c.commit.messageBody ?? '').slice(0, 300) })),
    said: said.filter((c) => c.body?.trim() && c.author && c.author.__typename !== 'Bot' && !/\[bot\]$/i.test(c.author.login))
      .map((c): Said => ({ who: c.author!.login, body: c.body.replace(/\[!\[Generated by[^\]]*\]\([^)]*\)\]\([^)]*\)/gi, '').trim().slice(0, 600), at: c.createdAt, url: c.url })),
  }
}

function ask(prompt: string, system: string): Promise<{ lines: TurnLine[]; costUsd: number; provider: ProviderId; tokens?: { input: number; output: number } }> {
  const p = providerFor('small')
  return new Promise((resolve, reject) => {
    const child = spawnAgent(p, ['-p', prompt, '--json-schema', JSON.stringify(schema), '--output-format', 'json', '--model', 'haiku', '--max-budget-usd', '0.1',
      '--tools', '', '--strict-mcp-config', '--disable-slash-commands', '--setting-sources', '', '--no-session-persistence',
      '--system-prompt', system], { cwd: tmpdir() })
    let out = ''
    child.stdout.on('data', (c: Buffer) => { out += c })
    child.on('error', reject)
    child.on('close', () => {
      try {
        const r = JSON.parse(out)
        if (!r.structured_output) throw new Error(String(r.result ?? 'no answer'))
        resolve({ lines: r.structured_output.lines, costUsd: r.total_cost_usd ?? 0, provider: p, tokens: tokensOf(r) })
      } catch (e) { reject(e) }
    })
  })
}

/** What one push changed, from the PR as GitHub has it now; records where it stands for the next one. */
export async function turn(pr: Pr, was: Turns) {
  const { commits, said } = await read(pr)
  const seen = new Set(was.seen)
  const fresh = was.seen ? commits.filter((c: { head: string }) => !seen.has(c.head)) : [] // first look: only learn the commits
  const since = said.filter((s) => s.at > was.at)
  const asks = since.filter((s) => s.who !== pr.author.login), answers = since.filter((s) => s.who === pr.author.login)
  const now: Turns = { ...was, sha: pr.headSha, at: new Date().toISOString(), seen: commits.map((c: { head: string }) => c.head) }
  if (was.seen && (fresh.length || asks.length || answers.length)) {
    const list = (xs: Said[]) => xs.map((s) => `- ${s.who} (${s.url}): ${s.body}`).join('\n') || '(none)'
    const prompt = [`Pull request "${pr.title}" by ${pr.author.login} got a new push. Name how it changed direction with this push.`,
      '- kind: changed, held or dropped. who and url: the reviewer and the comment the line answers, copied from below; leave both out when it answers no one.',
      '', 'New commits:', fresh.map((c: { head: string; body: string }) => `- ${c.head}${c.body ? `: ${c.body}` : ''}`).join('\n') || '(none)',
      '', 'Reviewers since the push before:', list(asks), '', `${pr.author.login}'s replies since then:`, list(answers)].join('\n')
    const r = await ask(prompt, await method('turns', 'Return only the structured output.'))
    addSpend(r.costUsd, r.provider, r.tokens)
    const urls = new Set(since.map((s) => s.url))
    // ponytail: a link the model made up is dropped, not checked further
    const lines = r.lines.map((l) => (l.url && !urls.has(l.url) ? { kind: l.kind, text: l.text, who: l.who } : l))
    if (lines.length) now.list = [{ at: now.at, from: was.sha, to: pr.headSha, lines, costUsd: r.costUsd }, ...was.list].slice(0, 30)
  }
  (state.turns ??= {})[pr.id] = now
  save()
}

let chain = Promise.resolve()
const queued = new Set<string>()
/** After a sync: every PR of yours or one you review whose head moved gets its turn worked out, one at a time. */
export function trackTurns() {
  const all = state.turns ??= {}
  for (const pr of Object.values(state.prs)) {
    if (pr.closed || !(pr.mine || pr.myReview || pr.requested) || !pr.headSha || queued.has(pr.id)) continue
    const was = all[pr.id]
    if (was && was.sha === pr.headSha && was.seen) continue
    queued.add(pr.id)
    chain = chain.then(() => turn(pr, was ?? { sha: pr.headSha, at: new Date().toISOString(), list: [] }))
      .catch((e) => console.error(`turns ${pr.id}:`, (e as Error).message)).finally(() => queued.delete(pr.id))
  }
}
