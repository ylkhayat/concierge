test('one session per PR or ticket: a run keeps it, a stack run only fills tickets that had none', async () => {
  const { remember, sessionOf } = await import('./runner.ts')
  const { state } = await import('./store.ts')
  state.sessions = { 'A-1': { id: 's-a', total: 1 } }
  remember(['A-1', 'B-2'], 's-new', 3) // a stack run of A-1 → B-2 in a new session
  assert.equal(sessionOf('A-1')?.id, 's-a') // A-1 keeps its own
  assert.deepEqual(sessionOf('B-2'), { id: 's-new', total: 3 })
  remember(['A-1'], 's-a', 5) // A-1's own session ran on: its cost moves up
  assert.equal(sessionOf('A-1')?.total, 5)
})

test('outside events: someone else\'s push, new comments waiting on you, a new verdict; your own push is not one', async () => {
  const { changesOf } = await import('./github.ts')
  const base = { id: 'a/b#1', mine: true, headSha: 'aaaaaaa1', awaiting: 1, unresolved: 2, reviewDecision: 'REVIEW_REQUIRED', closed: false, seenReviews: ['r1'] } as never
  const next = { ...(base as object), headSha: 'bbbbbbb2', awaiting: 3, reviewDecision: 'CHANGES_REQUESTED' } as never
  const reviews = [{ id: 'r1', who: 'lee', state: 'COMMENTED' }, { id: 'r2', who: 'lee', state: 'CHANGES_REQUESTED' }, { id: 'r3', who: 'me', state: 'COMMENTED' }]
  assert.deepEqual(changesOf(base, next, 'me', { pusher: 'jonas', commenters: ['lee'], reviews }), [
    { who: 'jonas', text: 'pushed bbbbbbb' },
    { who: 'lee', text: 'left 2 new comments waiting on you' },
    { who: 'lee', text: 'requested changes' }, // r1 seen before, r3 is yours
  ])
  const theirs = { id: 'a/b#2', mine: false, headSha: 'h', requested: false, myReview: { state: 'COMMENTED', commitId: 'h', submittedAt: '' }, seenReviews: [] } as never
  assert.deepEqual(changesOf(theirs, { ...(theirs as object), requested: true } as never, 'me'), [{ text: 'asked for your review again' }])
  assert.deepEqual(changesOf({ ...(base as object), seenReviews: undefined } as never, base, 'me', { reviews }), []) // first sight records, says nothing
  assert.deepEqual(changesOf(base, { ...(base as object), headSha: 'ccccccc3' } as never, 'me', { pusher: 'me' }), [])
  assert.deepEqual(changesOf(undefined, next, 'me'), []) // first sight is not news
})

